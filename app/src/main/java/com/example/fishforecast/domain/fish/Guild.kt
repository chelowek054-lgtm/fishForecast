package com.example.fishforecast.domain.fish

/**
 * Гильдия вида: хищник или мирная рыба.
 *
 * Деление грубое, но именно оно решает больше всего. Хищник охотится
 * глазами, поэтому его пики привязаны к свету и к укрытиям, откуда удобно
 * бить. Мирная рыба ищет корм, поэтому её тянет в заводи, к тростнику и
 * туда, куда ветер согнал планктон. Прикормка работает только для второй.
 */
enum class Guild {
    PREDATOR,
    PEACEFUL;

    companion object {
        /** Неизвестное значение считаем мирной рыбой: так ошибка безобиднее. */
        fun of(value: String?): Guild = when (value?.lowercase()) {
            "predator" -> PREDATOR
            else -> PEACEFUL
        }
    }
}
